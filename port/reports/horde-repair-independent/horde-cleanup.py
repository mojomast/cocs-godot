"""Remove only generated objects owned by this newly-created audit worktree."""
import hashlib
import json
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[3]
OUT = Path(__file__).resolve().parent
removed = []
for rel in ['godot/.godot', 'godot/content/generated']:
    path = ROOT / rel
    assert not subprocess.check_output(['git', 'ls-files', '--', rel], cwd=ROOT)
    if path.exists():
        shutil.rmtree(path)
        removed.append(rel)
content = ROOT / 'godot/content'
if content.exists() and not list(content.iterdir()): content.rmdir()
for path in (ROOT / 'godot/tests').rglob('*.gd.uid'):
    rel = str(path.relative_to(ROOT))
    if not subprocess.check_output(['git', 'ls-files', '--', rel], cwd=ROOT):
        # Every untracked UID in this fresh worktree was generated by our import.
        path.unlink()
        removed.append(rel)
link = ROOT / 'node_modules'
assert link.is_symlink()
target = link.resolve()
assert str(target) == '/home/mojo/.hermes-instances/fresh/workspace/cocs-godot-port/node_modules'
link.unlink()
removed.append('node_modules (owned symlink only)')
assert target.is_dir()
report = dict(removed=removed, primaryDependenciesPresent=True,
              generatedHashesPreservedIn='provenance.json',
              sourceMatchSHA256=hashlib.sha256((ROOT / 'game/core.mjs').read_bytes()).hexdigest(),
              ownedLiveProcessesAndListeners='reaped/absent and closed: provenance.json, all 3 launch summaries',
              protectedTrackedDiffEmpty=not subprocess.check_output(['git', 'diff', '--name-only'], cwd=ROOT))
(OUT / 'cleanup.json').write_text(json.dumps(report, indent=2) + '\n')
print(json.dumps(report, indent=2))
