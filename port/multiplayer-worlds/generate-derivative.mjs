#!/usr/bin/env node
// Explicit port-owned derivatives of locked source transport/room, generated
// byte-for-byte by narrow substitutions. Never edits server/ or game/ sources.
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const replace=(text,from,to,label)=>{if(!text.includes(from)||text.indexOf(from)!==text.lastIndexOf(from))throw Error(`Source seam drift ${label}`);return text.replace(from,to);};
const emit=(name,text)=>{const target=new URL(`./derived/${name}.mjs`,import.meta.url),content='// GENERATED by port/multiplayer-worlds/generate-derivative.mjs from locked source; do not hand-edit.\n'+text;if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==content)throw Error(`Stale derivative ${name}`);}else writeFileSync(target,content);};
{
 let text=readFileSync(new URL('../../game/core.mjs',import.meta.url),'utf8');
 text=text.replaceAll("from './","from '../../../game/");
 text=replace(text,"from '../../../game/payload.mjs'","from './payload.mjs'",'world payload');
 text="import {worldRace} from '../catalog.mjs';\n"+text;
 text=replace(text,'const track=getMap(mapId).race','const track=worldRace(mapId)','sports preflight');
 emit('core',text);
}
{
 let text=readFileSync(new URL('../../game/payload.mjs',import.meta.url),'utf8');
 text=text.replaceAll("from './","from '../../../game/");
 text=replace(text,'if(Object.isFrozen(navigation)){','if(Object.isFrozen(navigation)&&!arena.payloadPath){','wayline-specific route cache');
 text=replace(text,'if(options.navigation)return navigatedPath(arena,[start,end],options);',`if(options.navigation){
  const wayline=Array.isArray(arena.payloadPath)&&arena.payloadPath.length>2?arena.payloadPath.map(pair):null;
  if(wayline){
   if(wayline.some(p=>!p)||Math.hypot(wayline[0].x-start.x,wayline[0].z-start.z)>1||Math.hypot(wayline.at(-1).x-end.x,wayline.at(-1).z-end.z)>1)throw Error('Authored payload wayline endpoints mismatch team spawns');
   return wayline.slice(1).flatMap((point,i)=>navigatedPath(arena,[wayline[i],point],options).slice(i?1:0));
  }
  return navigatedPath(arena,[start,end],options);
 }`,'world payload anchors');
 emit('payload',text);
}
for(const name of ['room','rooms','game-server']){
  let text=readFileSync(new URL(`../../server/${name}.mjs`,import.meta.url),'utf8');
  text=text.replaceAll("from '../game/","from '../../../game/");
  if(name==='room'){
    text=text.replaceAll("from './","from '../../../server/");
    text="import {worldEntry,readWorld} from '../catalog.mjs';\nimport {worldMatchClass} from '../match.mjs';\n"+text;
    text=replace(text,"  this.mapId = resolveMapForMode(getMap(mapId).id, this.config.mode, { legacy: true });","  worldEntry(mapId,this.config.mode);\n  this.mapId = mapId;",'host world choice');
    text=replace(text,"  const mapId = resolveMapForMode(this.mapId, mode, { legacy: true });","  worldEntry(this.mapId,mode);\n  const mapId = this.mapId;",'start world choice');
    text=replace(text,"this.match = new Match('chatgpt'","this.match = new (worldMatchClass(this.mapId,mode))('chatgpt'",'constructor injection');
    text=replace(text,"  this.mapId = 'exchange';","  this.mapId = 'switchyard-ward';",'default map');
    text=text.replaceAll('mapId: this.match.arena.id, roundRevision: this.roundRevision','mapId: this.match.arena.id, geometryHash: readWorld(this.mapId).geometryHash, roundRevision: this.roundRevision');
    text=replace(text,'mapId: this.mapId, roundRevision: this.roundRevision','mapId: this.mapId, geometryHash: readWorld(this.mapId).geometryHash, roundRevision: this.roundRevision','new-round geometry');
  }
  if(name==='rooms'){
    text=text.replaceAll("from './room.mjs'","from './room.mjs'");
    text=replace(text,"this.defaultRoom = this.add(new Room('local'","this.defaultRoom = this.add(new Room('local'",'default room'); // structural anchor
  }
  if(name==='game-server'){
    text=text.replaceAll("from './rooms.mjs'","from './rooms.mjs'");
    text=text.replaceAll("from './","from '../../../server/");
    text=text.replace("from '../../../server/rooms.mjs'","from './rooms.mjs'");
  }
  emit(name,text);
}
