import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {recipes,seedFields} from './recipes.mjs';
import {loadTool} from './tool.mjs';
const {createContractSnapshot,validateJobsAgainstContracts}=await loadTool('engine-contracts.mjs');
const root=new URL('./',import.meta.url);
const supplemental=process.argv.includes('--supplemental');
const configName=supplemental?'supplemental.json':'live.json';
if(fs.existsSync(new URL(configName,root)))throw new Error('Refusing to replace an existing live recipe; preserve job IDs');
const write=(p,v)=>fs.writeFileSync(new URL(p,root),JSON.stringify(v)+'\n');
fs.mkdirSync(new URL('seeds/',root),{recursive:true});
fs.mkdirSync(new URL('contracts/',root),{recursive:true});
const contractDir=process.argv[2];
if(!contractDir)throw new Error('Usage: prepare.mjs <downloaded-contract-directory>');
const engine=JSON.parse(fs.readFileSync(`${contractDir}/blur-core-v1.json`));
const snapshot=createContractSnapshot([engine],{apiVersion:'v0.41.0'});
if(!fs.existsSync(new URL('contracts/engines.json',root)))write('contracts/engines.json',snapshot);
const schema=fs.readFileSync(`${contractDir}/openapi.json`);
fs.writeFileSync(new URL('contracts/openapi.json',root),schema);
write('contracts/schema-identity.json',{sha256:createHash('sha256').update(schema).digest('hex'),bytes:schema.length});
const jobs=recipes.filter((r,i)=>supplemental?i>=24:i<24).map((r,i)=>{const fields=seedFields(r);write(`seeds/${r.id}.json`,fields);return {id:r.id,engine:'blur-core-v1',credits:1,raw:r.id,params:{values:fields.height,strength:.055+(i%4)*.015,reach:0,style:i%2?'xy':'x',axes:[0,1],max_qubits:14},bake:{type:'raw-grid',name:r.id}};});
const config={version:1,contractSnapshot:'contracts/engines.json',jobs,emitters:[]};
const checks=validateJobsAgainstContracts(config,snapshot);
if(checks.errors.length)throw new Error(JSON.stringify(checks));
write(configName,config);
console.log(`Prepared and contract-validated ${jobs.length} authored 128² seeds; estimated ${jobs.length} credits.`);
